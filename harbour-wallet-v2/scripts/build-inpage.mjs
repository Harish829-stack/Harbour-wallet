// Bundles the page provider (src/inpage) into public/inpage.js, a single classic script with no imports. The extension registers it with
// chrome.scripting.registerContentScripts({ world: 'MAIN', runAt: 'document_start' }) (see src/background/provider/index.ts), exactly like Trust Wallet's `inpage.js`.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
await build({
  entryPoints: [root + 'src/inpage/index.ts'], outfile: root + 'public-production/inpage.js', bundle: true, format: 'iife', platform: 'browser', target: 'es2020',
  minify: true, legalComments: 'none', logLevel: 'info', banner: { js: '/* Harbour Wallet page provider (generated by scripts/build-inpage.mjs from src/inpage). */' },
});
