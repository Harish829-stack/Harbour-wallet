// Builds the traceability matrix: Feature ID x category -> test IDs, or an explicit "N/A because ..." rule. Any empty cell is a GAP (exit 1).
import fs from 'node:fs'; import path from 'node:path';
const Q = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const inv = fs.readFileSync(path.join(Q, 'FEATURE_INVENTORY.md'), 'utf8');
const partA = inv.slice(0, inv.indexOf('## Part B'));
const features = [...new Set([...partA.matchAll(/^\| ([A-Z]+-\d{2}) \|/gm)].map((m) => m[1]))];
const CATS = ['UNIT', 'INT', 'E2E', 'NEG', 'SEC', 'PROP', 'KAT', 'CONC', 'RES', 'MIG', 'CON', 'PERF', 'UI', 'REG'];
const planFiles = fs.readdirSync(path.join(Q, 'plan')).filter((f) => f.endsWith('.md')).sort();
const rows = [];
const expand = (spec) => {
  const out = [];
  for (const part of spec.split(/[\/,]/).map((s) => s.trim()).filter(Boolean)) {
    let m;
    if ((m = part.match(/^([A-Z]+)-\*$/))) out.push(...features.filter((f) => f.startsWith(m[1] + '-')));
    else if ((m = part.match(/^([A-Z]+)-(\d+)\.\.(?:([A-Z]+)-)?(\d+)$/))) { for (let i = +m[2]; i <= +m[4]; i++) out.push(`${m[1]}-${String(i).padStart(2, '0')}`); }
    else if ((m = part.match(/^([A-Z]+)-(\d+)$/))) out.push(`${m[1]}-${String(+m[2]).padStart(2, '0')}`);
    else if ((m = part.match(/^(\d+)$/)) && out.length) { const g = out[out.length - 1].split('-')[0]; out.push(`${g}-${String(+m[1]).padStart(2, '0')}`); }
  }
  return out.filter((f) => features.includes(f));
};
const byId = {};
for (const f of planFiles) for (const line of fs.readFileSync(path.join(Q, 'plan', f), 'utf8').split('\n')) {
  const c = line.split('|').map((s) => s.trim());
  if (!/^T-[A-Z]+-\d{3}$/.test(c[1] ?? '')) continue;
  const id = c[1];
  if (/^T-(KEY|SIG|DAPP|EXT|UX|SA|CH|DEFI|DATA|BE|GW|IDX|DB|X)-/.test(id)) { rows.push({ id, feats: expand(c[2]), cat: c[3], pri: c[4] }); byId[id] = rows[rows.length - 1]; }
  else if (/^T-REG-/.test(id)) rows.push({ id, refs: [...line.matchAll(/T-[A-Z]+-\d{3}/g)].map((m) => m[0]).filter((x) => x !== id), cat: 'REG', pri: c[4], commit: c[2] });
  else rows.push({ id, suite: true, cat: c[3], pri: c[4], covers: c[2] });
}
// REG rows without references, mapped by commit scope
const regDirect = { 'T-REG-001': ['DATA-04', 'BE-23'], 'T-REG-002': ['DAPP-17', 'GW-15'], 'T-REG-004': ['SA-07'], 'T-REG-005': ['DEFI-02', 'CH-07'], 'T-REG-007': ['CH-06'], 'T-REG-008': ['DEFI-01', 'DEFI-03'], 'T-REG-016': ['DAPP-18', 'BE-13'], 'T-REG-018': ['DEFI-03'], 'T-REG-026': ['EXT-14'], 'T-REG-027': ['SIG-13', 'KEY-12'], 'T-REG-028': ['EXT-14'], 'T-REG-029': ['EXT-14', 'X-08'], 'T-REG-031': ['UX-04'] };
for (const r of rows.filter((r) => r.cat === 'REG')) { const f = new Set(regDirect[r.id] ?? []); for (const ref of r.refs) for (const x of byId[ref]?.feats ?? []) f.add(x); r.feats = [...f]; }
// Parameterised suites -> features via Part C mapping
const partC = inv.slice(inv.indexOf('## Part C'));
const msgFeats = new Set(), pmFeats = new Set(), rtFeats = new Set();
for (const m of partC.matchAll(/^\| MSG-\d+ \| [^|]+\| [^|]+\| ([^|]+) \|/gm)) expand(m[1]).forEach((f) => msgFeats.add(f));
for (const m of partC.matchAll(/^\| PM-[\dA-Z]+ \|(?:[^|]*\|){6} ([^|]+) \|/gm)) expand(m[1]).forEach((f) => pmFeats.add(f));
for (const m of partC.matchAll(/^\| RT-\d+ \|(?:[^|]*\|){5} ([^|]+) \|/gm)) expand(m[1].replace(/ /g, '')).forEach((f) => rtFeats.add(f));
for (const r of rows.filter((r) => r.suite)) {
  if (r.id.startsWith('T-MSG')) r.feats = [...msgFeats];
  else if (r.id.startsWith('T-PM')) r.feats = [...pmFeats];
  else if (r.id.startsWith('T-RT')) r.feats = [...rtFeats];
  else if (r.id.startsWith('T-DBO')) r.feats = features.filter((f) => f.startsWith('DB-'));
  else if (r.id.startsWith('T-GOF')) r.feats = features.filter((f) => /^(BE|GW|IDX|DB)-/.test(f));
  else if (r.id.startsWith('T-EXP')) r.feats = features.filter((f) => /^(KEY|SIG|DAPP|EXT|UX|SA|CH|DEFI|DATA|X)-/.test(f));
}
// N/A rules: [feature regex, category, reason]
const NA = JSON.parse(fs.readFileSync(path.join(Q, 'tools', 'na-rules.json'), 'utf8'));
const cells = {}; for (const f of features) { cells[f] = {}; for (const c of CATS) cells[f][c] = []; }
for (const r of rows) for (const f of r.feats ?? []) if (cells[f]?.[r.cat]) cells[f][r.cat].push(r.id);
let gaps = []; let out = `\n## 17. Traceability matrix (generated by \`qa/tools/gen-matrix.mjs\`)\n\nEach cell lists the Test IDs for that Feature ID and category, or the explicit reason it does not apply (rule ids in \`qa/tools/na-rules.json\`). Parameterised suites (T-MSG/T-PM/T-RT/T-DBO/T-GOF/T-EXP) count for every feature their generated table maps to. **Gaps: see bottom line (must be 0).**\n\n| Feature | ${CATS.join(' | ')} |\n|---|${CATS.map(() => '---').join('|')}|\n`;
for (const f of features) {
  const row = CATS.map((c) => {
    const t = [...new Set(cells[f][c])];
    if (t.length) { const own = t.filter((x) => !/^T-(MSG|PM|RT|DBO|GOF|EXP)-/.test(x)); const suites = t.filter((x) => /^T-(MSG|PM|RT|DBO|GOF|EXP)-/.test(x)); return [...own, ...(suites.length ? [`+${suites.length} suite`] : [])].join(' '); }
    const rule = NA.find(([re, cat]) => (cat === c || cat === '*') && new RegExp(re).test(f));
    if (rule) return `N/A(${rule[3]})`;
    gaps.push(`${f}:${c}`); return '**GAP**';
  });
  out += `| ${f} | ${row.join(' | ')} |\n`;
}
out += `\nN/A reasons:\n\n${[...new Map(NA.map((r) => [r[3], r[2]])).entries()].map(([k, v]) => `- **${k}**: ${v}`).join('\n')}\n\nTotals: ${features.length} features × ${CATS.length} categories; tests defined: ${rows.length}; gaps: **${gaps.length}**${gaps.length ? ' → ' + gaps.join(', ') : ''}.\n`;
const counts = {}; for (const r of rows) { counts[r.cat] = (counts[r.cat] ?? 0) + 1; }
const pri = {}; for (const r of rows) pri[r.pri] = (pri[r.pri] ?? 0) + 1;
out += `\nTest counts by category: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}. By priority: ${Object.entries(pri).sort().map(([k, v]) => `${k} ${v}`).join(', ')}.\n`;
fs.writeFileSync(path.join(Q, 'plan', '90-matrix.generated.md'), out);
console.log('features', features.length, 'tests', rows.length, 'gaps', gaps.length); if (gaps.length) { console.log(gaps.join(' ')); process.exitCode = 1; }
